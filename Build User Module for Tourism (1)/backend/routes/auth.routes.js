const router = require('express').Router();
const { body } = require('express-validator');
const { register, login, getMe, logout, demoLogin } = require('../controllers/auth.controller');
const { protect } = require('../middleware/auth.middleware');
const registerRules = [body('name').trim().notEmpty(), body('email').isEmail(), body('password').isLength({ min: 6 })];
const loginRules = [body('email').isEmail(), body('password').notEmpty()];
router.post('/register', registerRules, register);
router.post('/login', loginRules, login);
router.post('/demo-login', demoLogin);
router.get('/me', protect, getMe);
router.post('/logout', protect, logout);
module.exports = router;
